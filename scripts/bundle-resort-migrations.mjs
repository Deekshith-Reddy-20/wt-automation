#!/usr/bin/env node
// Build the SQL-editor bundles in supabase/apply/, for projects managed through
// the Supabase SQL editor instead of `supabase db push`:
//
//   vfarms_resort_059_065.sql  migrations 059–065, for a project already at 058.
//   vfarms_full_setup.sql      every migration, for a project without the base
//                              CRM schema. Existing public tables (e.g. a schema
//                              made by another tool) are first renamed to
//                              legacy_pre_vfarms_<name>, data untouched.
//
// Each bundle is one transaction. Regenerate after changing any migration:
//
//   node scripts/bundle-resort-migrations.mjs          # write the bundles
//   node scripts/bundle-resort-migrations.mjs --check  # fail if one is out of date

import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..')
const dir = path.join(root, 'supabase', 'migrations')
const applyDir = path.join(root, 'supabase', 'apply')

const all = fs.readdirSync(dir).filter((f) => /^\d{3}_.*\.sql$/.test(f)).sort()
const resort = all.filter((f) => /^(059|06[0-5])_/.test(f))
if (resort.length !== 7) {
  console.error(`Expected migrations 059–065, found: ${resort.join(', ')}`)
  process.exit(1)
}

const body = (files) =>
  files
    .map((f) => `\n-- >>>>>>>>>> ${f}\n${fs.readFileSync(path.join(dir, f), 'utf8').replace(/^\uFEFF/, '').trimEnd()}\n`)
    .join('')

const resortBundle = `-- ============================================================
-- V-Farms resort schema: migrations ${resort.map((f) => f.slice(0, 3)).join(', ')} in one transaction.
-- GENERATED by scripts/bundle-resort-migrations.mjs — do not edit by hand.
--
-- Paste into Supabase → SQL Editor and run. Additive and idempotent:
-- creates tables, functions and policies; deletes no data. If any
-- statement fails, the whole transaction rolls back.
-- Requires migrations 001–058 (the base CRM schema) to be applied first.
-- Undo 063/064: supabase/rollback/063_vfarms_resort_automations_down.sql
-- (re-run 062 first).
-- ============================================================

BEGIN;

DO $$
BEGIN
  IF to_regprocedure('public.resolve_inbound_context(text, text, text[], jsonb)') IS NULL THEN
    RAISE EXCEPTION 'Base schema incomplete: apply supabase/migrations 001–058 before this bundle.';
  END IF;
END $$;
${body(resort)}
COMMIT;
`

const fullBundle = `-- ============================================================
-- V-Farms full database setup: migrations ${all[0].slice(0, 3)}–${all.at(-1).slice(0, 3)} in one transaction.
-- GENERATED by scripts/bundle-resort-migrations.mjs — do not edit by hand.
--
-- For a Supabase project that does NOT have this app's base schema yet
-- (no public.profiles). Paste into Supabase → SQL Editor and run.
--
-- 1. Every table already in the public schema is renamed to
--    legacy_pre_vfarms_<name>, with its indexes, sequences, rows and
--    policies untouched (nothing is dropped). Undo: drop the new tables
--    and rename the legacy ones back.
-- 2. All migrations run in order.
-- If any statement fails, the whole transaction rolls back and the
-- project is left exactly as it was.
--
-- A project that already has the base schema must use
-- vfarms_resort_059_065.sql instead; this file refuses to run there.
-- ============================================================

BEGIN;

DO $$
DECLARE
  t TEXT;
  r RECORD;
BEGIN
  IF to_regclass('public.profiles') IS NOT NULL THEN
    RAISE EXCEPTION 'This project already has the base schema (public.profiles exists). Use supabase/apply/vfarms_resort_059_065.sql instead.';
  END IF;
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' AND tablename NOT LIKE 'legacy\\_pre\\_vfarms\\_%' ORDER BY tablename LOOP
    IF to_regclass(format('public.%I', left('legacy_pre_vfarms_' || t, 63))) IS NOT NULL THEN
      RAISE EXCEPTION 'public.% exists and public.% already exists too; rename one of them and re-run.', t, left('legacy_pre_vfarms_' || t, 63);
    END IF;
    FOR r IN
      SELECT c.relname, CASE c.relkind WHEN 'S' THEN 'SEQUENCE' ELSE 'INDEX' END AS kind
      FROM pg_class c
      WHERE c.oid IN (SELECT indexrelid FROM pg_index WHERE indrelid = format('public.%I', t)::regclass)
         OR c.oid IN (SELECT objid FROM pg_depend WHERE refobjid = format('public.%I', t)::regclass AND deptype IN ('a', 'i') AND classid = 'pg_class'::regclass)
            AND c.relkind = 'S'
    LOOP
      EXECUTE format('ALTER %s public.%I RENAME TO %I', r.kind, r.relname, left('legacy_pre_vfarms_' || r.relname, 63));
    END LOOP;
    EXECUTE format('ALTER TABLE public.%I RENAME TO %I', t, left('legacy_pre_vfarms_' || t, 63));
    RAISE NOTICE 'Kept pre-existing public.% as public.% (data untouched).', t, left('legacy_pre_vfarms_' || t, 63);
  END LOOP;
END $$;
${body(all)}
COMMIT;
`

const outputs = [
  ['vfarms_resort_059_065.sql', resortBundle, resort.length],
  ['vfarms_full_setup.sql', fullBundle, all.length],
]

if (process.argv.includes('--check')) {
  const stale = outputs.filter(([name, content]) => {
    const file = path.join(applyDir, name)
    return !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content
  })
  if (stale.length) {
    console.error(`Out of date: ${stale.map(([n]) => `supabase/apply/${n}`).join(', ')}. Run: node scripts/bundle-resort-migrations.mjs`)
    process.exit(1)
  }
  console.log('Bundles are up to date.')
} else {
  fs.mkdirSync(applyDir, { recursive: true })
  for (const [name, content, count] of outputs) {
    fs.writeFileSync(path.join(applyDir, name), content)
    console.log(`Wrote supabase/apply/${name} (${count} migrations).`)
  }
}
